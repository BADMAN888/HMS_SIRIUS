UPDATE reservations
SET status = 'RESERVED'
WHERE status = 'CONFIRMED';

UPDATE rooms
SET status = CASE status
    WHEN 'RESERVED' THEN 'AVAILABLE'
    WHEN 'OUT_OF_SERVICE' THEN 'CLEANING'
    WHEN 'OUT_OF_ORDER' THEN 'CLEANING'
    ELSE status
END
WHERE status IN ('RESERVED', 'OUT_OF_SERVICE', 'OUT_OF_ORDER');
